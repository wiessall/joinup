#!/usr/bin/env python3
"""Rebuild fonts/bootstrap-icons-subset.woff2 and css/base/icons.css.

Keeps only the glyphs the FAO Design System CSS references plus the icon
names listed in WANT. Run from the theme folder:

  npm install --no-save bootstrap-icons@1.13.1 fao-design-system@3.6.5
  pip install fonttools brotli
  python3 scripts/build-icons.py

Add an icon: append its name (https://icons.getbootstrap.com) to WANT, rerun.
"""
import json, os, re, subprocess

NM = 'node_modules'
WANT = [
    'search', 'geo-alt-fill', 'chevron-right', 'chevron-down', 'chevron-left',
    'x-lg', 'funnel', 'share-fill', 'person-circle', 'bookmark', 'house-fill',
    'file-earmark-text', 'calendar-event', 'box-arrow-up-right', 'list', 'x',
    'question-circle', 'arrow-right',
]

ds = open(f'{NM}/fao-design-system/fao-theme.min.css').read()
names = json.load(open(f'{NM}/bootstrap-icons/font/bootstrap-icons.json'))
cps = {int(c, 16) for c in re.findall(r'content:"\\(f[0-9a-f]{3})"', ds)}
cps |= {names[n] for n in WANT}

subprocess.run([
    'pyftsubset', f'{NM}/bootstrap-icons/font/fonts/bootstrap-icons.woff2',
    '--unicodes=' + ','.join('U+%04X' % c for c in sorted(cps)),
    '--flavor=woff2', '--output-file=fonts/bootstrap-icons-subset.woff2',
    '--no-hinting', '--layout-features=', '--name-IDs=',
], check=True)

css = [
    '/* Generated by scripts/build-icons.py. Do not edit by hand. */',
    '@font-face{font-display:block;font-family:"bootstrap-icons";'
    'src:url("../../fonts/bootstrap-icons-subset.woff2") format("woff2");}',
    '.bi::before,[class^="bi-"]::before,[class*=" bi-"]::before{display:inline-block;'
    'font-family:bootstrap-icons!important;font-style:normal;font-weight:normal!important;'
    'line-height:1;vertical-align:-.125em;}',
]
css += ['.bi-%s::before{content:"\\%x";}' % (n, names[n]) for n in sorted(WANT)]
open('css/base/icons.css', 'w').write('\n'.join(css) + '\n')
print(len(cps), 'glyphs,', os.path.getsize('fonts/bootstrap-icons-subset.woff2'), 'bytes')
